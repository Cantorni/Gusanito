import base64
import binascii
from datetime import datetime
from typing import Literal
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, field_validator
from pydantic.alias_generators import to_camel

# Our own per-photo cap. The PWA already downscales to <=1280 px JPEG, well under it.
MAX_PHOTO_BYTES = 5 * 1024 * 1024
# Used as the Table Storage PartitionKey, which rejects / \ # ?
RESERVOIR_ID_PATTERN = r"^[A-Za-z0-9_.-]{1,100}$"

MediaType = Literal["image/jpeg", "image/png", "image/webp"]


class _Wire(BaseModel):
    """Request bodies use camelCase on the wire, like the rest of the PWA's JSON."""

    model_config = ConfigDict(alias_generator=to_camel, populate_by_name=True, extra="forbid")


class Location(_Wire):
    lat: float = Field(ge=-90, le=90)
    lng: float = Field(ge=-180, le=180)
    accuracy: float | None = Field(default=None, ge=0)


class PhotoIn(_Wire):
    media_type: MediaType
    data: str  # base64, without the data: URL prefix

    @field_validator("data")
    @classmethod
    def check_base64(cls, value: str) -> str:
        try:
            raw = base64.b64decode(value, validate=True)
        except binascii.Error as e:
            raise ValueError("data is not valid base64") from e
        if not raw:
            raise ValueError("photo is empty")
        if len(raw) > MAX_PHOTO_BYTES:
            raise ValueError(f"photo is larger than {MAX_PHOTO_BYTES // (1024 * 1024)} MB")
        return value

    def raw(self) -> bytes:
        return base64.b64decode(self.data)


class PhotoMeta(_Wire):
    name: str | None = Field(default=None, max_length=120)
    original_size: int | None = Field(default=None, ge=0)
    width: int | None = Field(default=None, ge=0)
    height: int | None = Field(default=None, ge=0)


class ReportIn(_Wire):
    # Generated by the PWA, so resending the same report never creates a duplicate.
    id: UUID
    reservoir_id: str | None = Field(default=None, pattern=RESERVOIR_ID_PATTERN)
    # What the extension officer said they see.
    label: Literal["armyworm", "not_armyworm", "unsure"] | None = None
    location: Location | None = None
    captured_at: datetime | None = None
    notes: str | None = Field(default=None, max_length=500)
    photos: list[PhotoIn] = Field(min_length=1, max_length=3)
    meta: PhotoMeta | None = None


SenalGusano = Literal[
    "hojas_ventana",
    "agujeros_irregulares",
    "excremento_en_cogollo",
    "larva_visible",
    "masa_de_huevos",
]


class Analysis(BaseModel):
    """What Claude returns for a report. Field names are Spanish, as in the project proposal."""

    calidad_fotos: Literal["buena", "aceptable", "no_sirve"]
    tipo_vegetacion: Literal[
        "maiz", "sorgo", "pasto", "otro_cultivo", "arboles_o_arbustos", "suelo_desnudo", "incierto"
    ]
    es_hospedero: Literal["si", "no", "incierto"]
    senales_gusano: list[SenalGusano] = Field(
        description="Señales de gusano cogollero visibles. Lista vacía si no hay ninguna."
    )
    severidad: Literal["ninguna", "baja", "media", "alta", "incierta"]
    confianza: float = Field(ge=0, le=1, description="Confianza en el diagnóstico, de 0 a 1.")
    requiere_revision_humana: bool
    nota_para_extensionista: str = Field(
        description="Una o dos frases simples en español sobre lo que se ve y qué hacer."
    )


Estado = Literal[
    "pendiente",
    "repetir_fotos",
    "revision_humana",
    "reservorio_confirmado",
    "hospedero_sin_senales",
    "descartado",
    "error_analisis",
]


def decide_estado(analysis: Analysis | None, min_confidence: float) -> Estado:
    if analysis is None:
        return "revision_humana"
    if analysis.calidad_fotos == "no_sirve":
        return "repetir_fotos"
    if analysis.requiere_revision_humana or analysis.confianza < min_confidence:
        return "revision_humana"
    if analysis.senales_gusano:
        return "reservorio_confirmado"
    if analysis.es_hospedero == "no":
        return "descartado"
    if analysis.es_hospedero == "si":
        return "hospedero_sin_senales"
    return "revision_humana"


def agrees_with_officer(label: str | None, analysis: Analysis | None) -> bool | None:
    """Whether Claude agrees with the officer's label. None when there is nothing to compare."""
    if label in (None, "unsure") or analysis is None or analysis.calidad_fotos == "no_sirve":
        return None
    return bool(analysis.senales_gusano) == (label == "armyworm")


class AlertIn(_Wire):
    risk_level: Literal["low", "medium", "high"]
    distance_km: float = Field(gt=0, le=50)
    direction: Literal["north", "south", "east", "west", "northeast", "northwest", "southeast", "southwest"] | None = None
    days_to_act: int = Field(ge=0, le=30)
    language: Literal["es", "en", "ny"] = "en"


MAX_SMS_CHARS = 160


class AlertMessage(BaseModel):
    sms: str = Field(description=f"SMS text, at most {MAX_SMS_CHARS} characters.")
    voice: str = Field(description="Script for a voice call of about 20 seconds.")
